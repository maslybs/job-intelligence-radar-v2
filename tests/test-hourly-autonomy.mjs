import {strict as assert} from "node:assert";
import {readFileSync} from "node:fs";
import {utcHourSlot,hourlyWorkflowId,needsHourlyRescue} from "../src/features/scheduler/hourly-autonomy.js";
assert.equal(utcHourSlot(Date.parse("2026-10-23T01:00:00Z")),"2026102301");
assert.equal(utcHourSlot(Date.parse("2026-10-23T01:20:00Z")),"2026102301");
assert.equal(hourlyWorkflowId("2026102301"),"hourly-auto-2026102301");
assert.equal(hourlyWorkflowId("2026102301","hourly-rescue"),"hourly-rescue-2026102301");
assert.throws(()=>utcHourSlot("bad"));assert.throws(()=>hourlyWorkflowId("hello"));
assert(!needsHourlyRescue({status:"running"},null,"2026102301"));
assert(!needsHourlyRescue({status:"queued"},null,"2026102301"));
assert(!needsHourlyRescue({status:"complete",output:{state:"completed"}},null,"2026102301"));
assert(!needsHourlyRescue(null,{slot:"2026102301",state:"completed",origin:"scheduled"},"2026102301"));
assert(needsHourlyRescue(null,{slot:"2026102300",state:"completed",origin:"scheduled"},"2026102301"));
assert(needsHourlyRescue(null,{slot:"2026102301",state:"completed",origin:"manual_probe"},"2026102301"));
assert(needsHourlyRescue({status:"errored"},null,"2026102301"));
assert(needsHourlyRescue({status:"terminated"},null,"2026102301"));
assert(needsHourlyRescue({status:"complete",output:{state:"degraded"}},null,"2026102301"));
const src=readFileSync("src/workflows/action-registry.js","utf8");
const cron=readFileSync("src/scheduler/scheduled-handler.js","utf8");
assert(cron.includes('params:{action:"hourly_pipeline",slot,recovery:false}'));
assert(cron.includes(".format(scheduledAt)"),"delayed cron must use scheduled time");
assert(cron.includes("scheduledAt.getUTCMinutes()"));
assert(cron.includes('params:{action:"hourly_pipeline",slot,recovery:true}'));
assert(!cron.includes('()=>scan(env)'));
assert(!cron.includes('()=>cloudUpworkScan(env)'));
assert(src.includes('"hourly_pipeline": executeHourlyPipelineAction'));
console.log("PASS: autonomous hourly scheduling, no heavy scan in cron, once-per-hour ID, rescue status guard");
