import {RADAR_SETTINGS} from "../src/config/radar.generated.js";
import {strict as assert} from "node:assert";
import {readFileSync} from "node:fs";
import {listingIsActionable,sourceIsActionable,excludedTopicLead} from "../src/features/discovery/source-accessibility.js";
import {focusedRedditTargets} from "../src/features/reddit/reddit-expertise.js";
import {selectDouCandidates} from "../src/features/dou/dou-review.js";
import {chooseActionableReview} from "../src/features/jobs/actionable-review.js";
const good={source:"DOU · Browser",title:"AI Automation Engineer",url:"https://jobs.dou.ua/companies/foo/vacancies/375014/",description:"Python n8n RAG LLM APIs",kind:"buyer",score:90,geo:"unknown",state:"unread",id:"abc"};
assert(listingIsActionable(good));
const excludesWp=RADAR_SETTINGS.jobs.criteria.excludeTechnologies.some(x=>/wordpress|woocommerce/i.test(x));
assert.equal(listingIsActionable({...good,title:"Senior WordPress Developer"}),!excludesWp);
assert.equal(listingIsActionable({...good,title:"WooCommerce automation API"}),!excludesWp);
assert.equal(listingIsActionable({...good,description:"Implement a WordPress plugin for customer portal and n8n"}),!excludesWp);
assert.equal(listingIsActionable({...good,source:"Reddit r/ProWordPress"}),!excludesWp);
assert.equal(sourceIsActionable({name:"WordPress Jobs · Direct Contact",url:"https://jobs.wordpress.net/feed/"}),!excludesWp);
assert.equal(excludedTopicLead({...good,source:"Reddit r/woocommerce"}),excludesWp);
assert.equal(chooseActionableReview([{...good,url:"https://himalayas.app/jobs/123"}, {...good,id:"blocked",title:"WordPress Developer",url:"https://himalayas.app/jobs/144"}]).length,excludesWp?1:2);
assert.equal(selectDouCandidates([{...good,id:"x",score:91,title:"WordPress plugin developer"},good]).length,excludesWp?1:2);
assert(!focusedRedditTargets().some(t=>/wordpress|woocommerce|elementor|gutenberg/i.test(t.term)));
const main=readFileSync("src/scheduler/scheduled-handler.js","utf8");
const reddit=readFileSync("src/features/reddit/reddit-mcp-workflow.js","utf8");
const dou=readFileSync("src/features/dou/dou-browser-workflow.js","utf8");
const adaptive=readFileSync("src/features/reddit/reddit-adaptive.js","utf8");
assert(!main.includes('["WordPress Jobs'));
assert(main.includes("reviewDue:scheduledAt.getUTCMinutes()%10===0"));
assert(main.includes("scheduledAt.getUTCMinutes()%10===5"));
assert(!main.includes("scheduledAt.getUTCMinutes()%10!==0)return;"));
assert(reddit.includes("pickRedditTargets(env,1)"));
assert(reddit.includes("reviewDue!==false"));
assert(dou.includes("douBatch(Number.isFinite(index)?index:0,1)"));
assert(adaptive.includes("UPDATE reddit_targets SET retired=1"));
console.log("PASS candidate-specific WordPress preference, Reddit 5m, DOU 10m, bounded browser visits");
